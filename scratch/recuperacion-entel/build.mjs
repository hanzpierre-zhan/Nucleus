import fs from 'node:fs/promises';
import {Workbook, SpreadsheetFile} from '@oai/artifact-tool';
const source = JSON.parse(await fs.readFile(new URL('./sites.json', import.meta.url), 'utf8'));
const wb = Workbook.create();
const sh = wb.worksheets.add('Cobra Site');
const n = source.rows.length + 1;
sh.getRange(`A1:J${n}`).values = [source.columns, ...source.rows];
sh.showGridLines = false;
sh.getRange(`A1:J${n}`).format.font = {name:'Arial',size:10};
sh.getRange(`A1:J${n}`).format.verticalAlignment = 'center';
sh.getRange('A1:J1').format = {fill:'#173E76',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},wrapText:true,rowHeight:32};
sh.getRange(`A2:A${n}`).setNumberFormat('@');
sh.getRange(`H2:I${n}`).setNumberFormat('0.000000');
for (const [col,width] of [['A',18],['B',38],['C',16],['D',22],['E',24],['F',26],['G',65],['H',18],['I',18],['J',25]]) sh.getRange(`${col}1:${col}${n}`).format.columnWidth=width;
sh.tables.add(`A1:J${n}`,true,'CobraSites');
sh.freezePanes.freezeRows(1);
sh.getRange('L1').values=[['Reconstruido desde el respaldo del maestro SITE del 28/09/2026. No es el archivo original eliminado.']];
sh.getRange('L1').format.columnWidth=115;
wb.recalculate();
console.log((await wb.inspect({kind:'table',range:'\'Cobra Site\'!A1:D4',tableMaxRows:4,tableMaxCols:4,maxChars:900})).ndjson);
const dir='outputs/recuperacion-entel';
await fs.mkdir(dir,{recursive:true});
const blob=await wb.render({sheetName:'Cobra Site',range:'A1:F10',scale:1,format:'png'});
await fs.writeFile(`${dir}/preview.png`,new Uint8Array(await blob.arrayBuffer()));
await (await SpreadsheetFile.exportXlsx(wb)).save(`${dir}/Cobra Site reconstruido.xlsx`);
console.log(`Exportadas ${source.rows.length} filas.`);
